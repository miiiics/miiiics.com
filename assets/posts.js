/* Absolute prefix to the site root, set by site.js from its own script URL so it is
   correct at any page depth. Falls back to one level up for safety. */
function siteBase() {
  return window.SITE_BASE || '../';
}

function escapeHtml(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function iconSpan(file) {
  var url = siteBase() + 'assets/icons/' + file;
  return '<span class="badge-svg-icon" style="-webkit-mask-image:url(' + url + ');mask-image:url(' + url + ')" aria-hidden="true"></span> ';
}

function categoryBadge(cat) {
  var d = window.BADGE_DEFS[cat];
  if (!d) return '';
  return '<a href="' + siteBase() + d.path + '" class="badge ' + d.cls + '">' +
    (d.icon ? iconSpan(d.icon) : '') + d.label + '</a>';
}

/* Project badge: collapsed it reads "⚒ Projects"; on hover the nested span expands
   to reveal " — <project name>". Always rendered last. The divider is only drawn when
   there are category badges to divide it from — a post may legitimately have none. */
function projectBadge(slug, withDivider) {
  var p = window.PROJECTS[slug];
  if (!p) return '';
  return (withDivider ? '<span class="badge-divider" aria-hidden="true">|</span>' : '') +
    '<a href="' + siteBase() + 'projects/' + slug + '/" class="badge badge-project" ' +
    'title="Project: ' + escapeHtml(p.name) + '">⚒ Projects' +
    '<span class="project-name"> — ' + escapeHtml(p.name) + '</span></a>';
}

/* Category ordering, used for both badges and the nav: alphabetical by key, with
   'misc' always last since it is the catch-all. */
function catCompare(a, b) {
  if (a === b) return 0;
  if (a === 'misc') return 1;
  if (b === 'misc') return -1;
  return a < b ? -1 : 1;
}

/* Category badges first, then the project badge. `catsOverride` lets the project page
   show the union of every category used across that project on its intro post. */
function badgeRow(post, catsOverride) {
  var cats = (catsOverride || post.cats || []).slice().sort(catCompare);
  var catHtml = cats.map(categoryBadge).join('');
  return catHtml + (post.project ? projectBadge(post.project, !!catHtml) : '');
}

/* Every category used by any post in a project, deduped and sorted. */
window.projectCats = function (slug) {
  var seen = {};
  window.POSTS.forEach(function (p) {
    if (p.project === slug) (p.cats || []).forEach(function (c) { seen[c] = true; });
  });
  return Object.keys(seen).sort();
};

/* Posts belonging to a project: the intro post first regardless of date, then the
   rest in POSTS order (newest first). */
window.projectPosts = function (slug) {
  var all = window.POSTS.filter(function (p) { return p.project === slug; });
  var intro = all.filter(function (p) { return p.projectIntro; });
  var rest = all.filter(function (p) { return !p.projectIntro; });
  return intro.concat(rest);
};

function galleryDotOpacity(dist) {
  return [1, 0.6, 0.3, 0.1][dist] || 0;
}

