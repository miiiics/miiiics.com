window.galleryGoto = function (gid, idx) {
  var el = document.getElementById(gid);
  if (!el) return;
  var imgs = window.GALLERIES[gid];
  var total = imgs.length;
  if (idx < 0 || idx >= total) return;
  var currentIdx = parseInt(el.dataset.index);
  if (idx === currentIdx) return;
  var dir = idx > currentIdx ? 1 : -1;
  var wrapper = el.querySelector('.image-wrapper');
  var outImg = wrapper.querySelector('img');

  wrapper.style.height = wrapper.offsetHeight + 'px';
  wrapper.style.position = 'relative';
  wrapper.style.overflow = 'hidden';
  outImg.style.position = 'absolute';
  outImg.style.top = '0';
  outImg.style.left = '0';
  outImg.style.width = '100%';

  var inImg = document.createElement('img');
  inImg.src = siteBase() + imgs[idx].src;
  inImg.alt = imgs[idx].caption || '';
  inImg.style.position = 'absolute';
  inImg.style.top = '0';
  inImg.style.left = '0';
  inImg.style.width = '100%';
  inImg.style.transform = 'translateX(' + (dir * 100) + '%)';
  wrapper.appendChild(inImg);
  inImg.offsetHeight; // force reflow

  var ease = '0.45s cubic-bezier(0.25, 0.46, 0.45, 0.94)';
  outImg.style.transition = 'transform ' + ease;
  inImg.style.transition = 'transform ' + ease;
  outImg.style.transform = 'translateX(' + (-dir * 100) + '%)';
  inImg.style.transform = 'translateX(0)';

  var track = el.querySelector('.gallery-dots-track');
  if (track) track.style.transform = 'translateX(' + ((total - 1) / 2 - idx) * 18 + 'px)';
  var dots = el.querySelectorAll('.gallery-dot');
  dots.forEach(function (d, i) {
    d.classList.toggle('gallery-dot-active', i === idx);
    d.style.opacity = galleryDotOpacity(Math.abs(i - idx));
  });
  // Toggle a class rather than `display`, so the flex row keeps its width and the image
  // does not shift when an arrow is hidden at either end.
  el.querySelector('.gallery-prev').classList.toggle('is-hidden', idx === 0);
  el.querySelector('.gallery-next').classList.toggle('is-hidden', idx === total - 1);

  setTimeout(function () {
    wrapper.removeChild(outImg);
    inImg.style.cssText = '';
    wrapper.style.height = '';
    wrapper.style.position = '';
    wrapper.style.overflow = '';
    el.dataset.index = idx;
    var caption = el.querySelector('.image-caption');
    if (caption) {
      caption.textContent = imgs[idx].caption || '';
      caption.style.display = imgs[idx].caption ? '' : 'none';
    }
  }, 450);
};

window.galleryNav = function (gid, dir) {
  var el = document.getElementById(gid);
  if (!el) return;
  window.galleryGoto(gid, parseInt(el.dataset.index) + dir);
};

function renderInline(text) {
  /* Link TARGETS are stashed behind placeholders first, because URLs routinely contain
     `_` (e.g. wikipedia.org/wiki/Analysis_paralysis) and the emphasis regexes below would
     otherwise pair that underscore with a real one later in the paragraph and swallow
     everything between them. Link LABELS stay exposed, so emphasis still works inside them. */
  var urls = [];
  var stashed = text.replace(/\[([^\]]+)\]\(([^)]+)\)/g, function (m, label, url) {
    urls.push(url);
    return '[' + label + '](\u0000' + (urls.length - 1) + '\u0000)';
  });

  return stashed
    .replace(/\*_([^*_]+)_\*/g, '<strong><em>$1</em></strong>')
    .replace(/_\*([^*_]+)\*_/g, '<strong><em>$1</em></strong>')
    .replace(/\*([^*]+)\*/g, '<strong>$1</strong>')
    .replace(/_([^_]+)_/g, '<em>$1</em>')
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g,
      '<a href="$2" target="_blank" rel="noopener noreferrer">$1</a>')
    .replace(/\u0000(\d+)\u0000/g, function (m, i) { return urls[Number(i)]; });
}

/* Renders one <article>. `catsOverride` is used only by the project page's intro post. */
function renderArticle(p, catsOverride) {
    var badges = badgeRow(p, catsOverride);
    var hasBody = p.body && p.body.length;
    var html = '';
    html += '<article class="post' + (hasBody ? ' post-has-body' : '') + '"><div class="post-meta">' + badges + '<span>' + p.date + '</span></div>';

    // Title: plain text when no url, linked when url is present
    if (p.url) {
      html += '<h2 class="post-title"><a href="' + p.url + '" target="_blank" rel="noopener">' + p.title + '</a></h2>';
    } else {
      html += '<h2 class="post-title">' + p.title + '</h2>';
    }

    // YouTube embed
    if (p.embedSrc) {
      html += '<div class="video-wrapper"><iframe width="560" height="315" src="' + p.embedSrc + '" title="YouTube video player" frameborder="0" allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share" referrerpolicy="strict-origin-when-cross-origin" allowfullscreen></iframe></div>';
    }

    // Body blocks: paragraphs and inline images
    if (p.body && p.body.length) {
      html += '<div class="post-body">';
      p.body.forEach(function (block) {
        if (block.type === 'p') {
          html += '<p>' + renderInline(block.text) + '</p>';
        } else if (block.type === 'img') {
          // `transparent: true` drops the frame — see .image-plain in site.css.
          html += '<div class="image-wrapper' + (block.transparent ? ' image-plain' : '') +
            '"><img src="' + siteBase() + block.src + '" alt="' + escapeHtml(block.caption || '') + '"></div>';
          if (block.caption) {
            html += '<p class="image-caption">' + block.caption + '</p>';
          }
        } else if (block.type === 'gallery') {
          var gid = 'gallery-' + (++_gallerySeq);
          var imgs = block.images;
          window.GALLERIES[gid] = imgs;
          var first = imgs[0] || {};
          html += '<div class="gallery" id="' + gid + '" data-index="0">';
          html += '<div class="gallery-image-area">';
          html += '<button class="gallery-btn gallery-prev is-hidden" onclick="galleryNav(\'' + gid + '\',-1)" aria-label="Previous image">&#8249;</button>';
          html += '<div class="image-wrapper' + (block.transparent ? ' image-plain' : '') +
            '"><img src="' + siteBase() + first.src + '" alt="' + escapeHtml(first.caption || '') + '"></div>';
          html += '<button class="gallery-btn gallery-next' + (imgs.length <= 1 ? ' is-hidden' : '') + '" onclick="galleryNav(\'' + gid + '\',1)" aria-label="Next image">&#8250;</button>';
          html += '</div>';
          if (imgs.length > 1) {
            var initShift = ((imgs.length - 1) / 2) * 18;
            html += '<div class="gallery-dots"><div class="gallery-dots-track" style="transform:translateX(' + initShift + 'px)">';
            imgs.forEach(function (_, i) {
              html += '<span class="gallery-dot' + (i === 0 ? ' gallery-dot-active' : '') + '" onclick="galleryGoto(\'' + gid + '\',' + i + ')" style="opacity:' + galleryDotOpacity(i) + '"></span>';
            });
            html += '</div></div>';
          }
          if (first.caption) html += '<p class="image-caption">' + first.caption + '</p>';
          html += '</div>';
        } else if (block.type === 'video') {
          html += '<div class="video-wrapper"><iframe width="560" height="315" src="' + block.embedSrc + '" title="YouTube video player" frameborder="0" allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share" referrerpolicy="strict-origin-when-cross-origin" allowfullscreen></iframe></div>';
          if (block.caption) {
            html += '<p class="image-caption">' + block.caption + '</p>';
          }
        }
      });
      html += '</div>';
    }

    html += '</article>';
    return html;
}

/* Collapses any post body taller than 480px behind a "Show More" button.
   Automatic — there is no per-post flag. Runs after every render. */
function applyShowMore(container) {
  container.querySelectorAll('.post-body').forEach(function (body) {
    // The "About this project" panel is already a collapse; don't nest a second one.
    if (body.closest && body.closest('.project-about-panel')) return;
    if (body.scrollHeight > 480) {
      body.classList.add('post-body-collapsed');
      var btn = document.createElement('button');
      btn.className = 'show-more-btn';
      btn.textContent = 'Show More ↓';
      btn.onclick = function () {
        var fullHeight = body.scrollHeight;
        body.style.maxHeight = '320px';
        body.style.overflow = 'hidden';
        body.classList.remove('post-body-collapsed');
        body.offsetHeight; // force reflow so transition fires
        body.style.transition = 'max-height 1.1s ease-in-out';
        body.style.maxHeight = fullHeight + 'px';
        btn.remove();
        setTimeout(function () { body.style.cssText = ''; }, 1110);
      };
      body.parentNode.insertBefore(btn, body.nextSibling);
    }
  });
}

function paintInto(containerId, html, emptyMsg) {
  var container = document.getElementById(containerId);
  if (!container) return;
  container.innerHTML = html || '<p class="empty-state">' + emptyMsg + '</p>';
  applyShowMore(container);
}

/* ── Sort order ──
   POSTS is maintained newest-first and nothing parses the date strings (they are display
   text, and an intro post's is a range like 'June 2026 - Present'). So ordering is done by
   array position: 'newest' is as-authored, 'oldest' is reversed. */
var sortDir = 'newest';

/* Remembers the last render so the toggle can repeat it. */
var lastRender = null;

function applySort(posts) {
  return sortDir === 'oldest' ? posts.slice().reverse() : posts;
}

/* Rendered as the first child of the post container, so a re-render replaces it. */
function sortControlHtml() {
  var newest = sortDir === 'newest';
  return '<div class="sort-row">' +
    '<button type="button" class="sort-btn" onclick="toggleSort()" aria-live="polite" ' +
    'title="Switch to ' + (newest ? 'oldest' : 'newest') + ' first">' +
    '<span class="sort-arrow" aria-hidden="true">' + (newest ? '↓' : '↑') + '</span>' +
    '<span>' + (newest ? 'Newest first' : 'Oldest first') + '</span>' +
    '</button></div>';
}

window.toggleSort = function () {
  sortDir = sortDir === 'newest' ? 'oldest' : 'newest';
  if (!lastRender) return;
  if (lastRender.kind === 'project') {
    window.renderProjectPosts(lastRender.containerId, lastRender.arg, lastRender.opts);
  } else {
    window.renderPosts(lastRender.containerId, lastRender.arg, lastRender.opts);
  }
  // Keep the button under the cursor after the list redraws.
  var btn = document.querySelector('.sort-btn');
  if (btn) btn.focus();
};

/* Home (pageCat null) and category pages.
   Project description posts are deliberately excluded everywhere here — they exist to
   introduce a project and belong only on that project's own page. */
window.renderPosts = function (containerId, pageCat, opts) {
  opts = opts || {};
  lastRender = { kind: 'posts', containerId: containerId, arg: pageCat, opts: opts };

  var posts = window.POSTS.filter(function (p) { return !p.projectIntro; });
  if (pageCat) {
    posts = posts.filter(function (p) { return (p.cats || []).indexOf(pageCat) !== -1; });
  }
  // A sort control over fewer than two posts would do nothing visible.
  var control = (opts.sort && posts.length > 1) ? sortControlHtml() : '';
  var body = applySort(posts).map(function (p) { return renderArticle(p); }).join('');
  paintInto(containerId, body ? control + body : '', 'Nothing here yet — check back soon.');
};

/* Expand/collapse the "About this project" panel. Animates max-height, then clears it
   so the panel can reflow freely (images loading, viewport resize) once open. */
window.toggleProjectAbout = function (btn) {
  var panel = btn.nextElementSibling;
  if (!panel) return;
  var open = btn.getAttribute('aria-expanded') === 'true';

  if (open) {
    panel.style.maxHeight = panel.scrollHeight + 'px';
    panel.offsetHeight; // force reflow so the transition runs from a real height
    panel.style.maxHeight = '0px';
    btn.setAttribute('aria-expanded', 'false');
    btn.classList.remove('open');
  } else {
    panel.style.maxHeight = panel.scrollHeight + 'px';
    btn.setAttribute('aria-expanded', 'true');
    btn.classList.add('open');
    setTimeout(function () {
      if (btn.getAttribute('aria-expanded') === 'true') panel.style.maxHeight = 'none';
    }, 450);
  }
};

/* A single project page. The intro post leads regardless of date, shows the union of
   every category used across the project, and is collapsed behind "About this project". */
window.renderProjectPosts = function (containerId, slug, opts) {
  opts = opts || {};
  lastRender = { kind: 'project', containerId: containerId, arg: slug, opts: opts };

  var unionCats = window.projectCats(slug);
  var all = window.projectPosts(slug);
  var intro = all.filter(function (p) { return p.projectIntro; })[0];
  var rest = all.filter(function (p) { return !p.projectIntro; });

  var html = '';

  // The description post stays pinned above everything, whichever way the rest is sorted.
  if (intro) {
    html += '<section class="project-about">' +
      '<button type="button" class="project-about-toggle" aria-expanded="false" ' +
      'onclick="toggleProjectAbout(this)">' +
      '<span class="project-about-chevron" aria-hidden="true">▸</span>' +
      '<span>About this Project</span></button>' +
      '<div class="project-about-panel">' + renderArticle(intro, unionCats) + '</div>' +
      '</section>';
  }

  if (opts.sort !== false && rest.length > 1) html += sortControlHtml();
  html += applySort(rest).map(function (p) { return renderArticle(p); }).join('');

  paintInto(containerId, html, 'No posts in this project yet — check back soon.');
};

/* The /projects/ index: one card per project. */
window.renderProjectIndex = function (containerId) {
  var slugs = Object.keys(window.PROJECTS);
  var html = slugs.map(function (slug) {
    var p = window.PROJECTS[slug];
    var n = window.POSTS.filter(function (x) { return x.project === slug; }).length;
    return '<a class="project-card" href="' + siteBase() + 'projects/' + slug + '/">' +
      '<h2>' + escapeHtml(p.name) + '</h2>' +
      // Blurb goes through renderInline (trusted content, same as post bodies) so it can
      // carry *bold*/_italic_ or raw inline HTML.
      (p.blurb ? '<p>' + renderInline(p.blurb) + '</p>' : '') +
      '<span class="project-count">' + n + (n === 1 ? ' post' : ' posts') + '</span></a>';
  }).join('');
  paintInto(containerId, html, 'No projects yet — check back soon.');
};
